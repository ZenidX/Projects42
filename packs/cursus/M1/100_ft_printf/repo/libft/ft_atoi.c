#include "libft.h"

int	ft_atoi(const char *nptr)
{
	size_t	i;
	int		s;
	int		r;

	s = 1;
	r = 0;
	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '+' || nptr[i] == '-')
	{
		if (nptr[i] == '-')
			s = -s;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9' && nptr[i])
	{
		r = r * 10 + s * (nptr[i] - '0');
		i++;
	}
	return (r);
}
