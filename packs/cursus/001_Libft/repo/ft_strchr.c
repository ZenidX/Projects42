#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	char	*p;

	p = (char *) s;
	while (*p != (char) c && *p)
		p++;
	if (!(*p) && c != 0)
		return (NULL);
	else
		return (p);
}
