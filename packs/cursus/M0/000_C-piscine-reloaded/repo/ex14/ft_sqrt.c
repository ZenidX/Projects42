#include <unistd.h>

int	ft_sqrt(int nb)
{
	int	i;

	i = 1;
	while (i * i != nb && i < nb)
		i++;
	if (nb == 1)
		return (1);
	if (i >= nb)
		return (0);
	else
		return (i);
}
