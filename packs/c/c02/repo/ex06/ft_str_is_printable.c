#include <unistd.h>

int	ft_str_is_printable(char *str)
{
	int	i;
	int	f;

	f = 1;
	i = 0;
	while (str[i] && f == 1)
	{
		if (!(str[i] >= 31 && str[i] != 127))
			f = 0;
		i++;
	}
	return (f);
}
