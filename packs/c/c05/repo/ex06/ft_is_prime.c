#include <unistd.h>

int	ft_is_prime(int nb)
{
	int	i;

	if (nb < 2)
		return (0);
	i = 2;
	while (i < nb)
	{
		if (nb % i == 0 || - nb % i == 0)
			return (0);
		i++;
	}
	return (1);
}
