#include <unistd.h>

int	ft_str_is_alpha(char *str)
{
	int	i;
	int	f;

	f = 1;
	i = 0;
	while (str[i] && f == 1)
	{
		if (!((str[i] >= 'a' && str[i] <= 'z')
				|| (str[i] >= 'A' && str[i] <= 'Z')))
			f = 0;
		i++;
	}
	return (f);
}
