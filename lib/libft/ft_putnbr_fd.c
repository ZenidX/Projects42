#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	d;
	long	nl;

	nl = n;
	if (n < 0)
	{
		write(fd, "-", 1);
		nl = -nl;
	}
	if (nl / 10 != 0)
		ft_putnbr_fd(nl / 10, fd);
	d = nl % 10 + '0';
	write(fd, &d, 1);
}
